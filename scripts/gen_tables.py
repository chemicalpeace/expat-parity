#!/usr/bin/env python3
"""Generate Rust table data from the vendored libexpat headers.

Usage: scripts/gen_tables.py          # (re)write the generated files
       scripts/gen_tables.py --check  # exit 1 if they are out of date

Sources (crates/expat-oracle/vendor/expat/lib, libexpat R_2_9_0):
  asciitab.h, iasciitab.h, latin1tab.h, utf8tab.h -> crates/expat/src/chartab/data.rs
  nametab.h                                        -> crates/expat/src/naming/data.rs
"""
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), ".."))
LIB = os.path.join(ROOT, "crates/expat-oracle/vendor/expat/lib")
HEADER = """// @generated by scripts/gen_tables.py from libexpat R_2_9_0
// (crates/expat-oracle/vendor/expat/lib/{src}). Do not edit by hand.
// Copyright (c) 1997-2000 Thai Open Source Software Center Ltd and
// Copyright (c) 2000-2025 Expat maintainers; MIT licensed (see NOTICE).
"""


def strip_comments(s):
    return re.sub(r"/\*.*?\*/", "", s, flags=re.S)


def bt_list(name):
    src = strip_comments(open(os.path.join(LIB, name)).read())
    items = re.findall(r"\bBT_([A-Z0-9]+)\b", src)
    assert len(items) == 128, (name, len(items))
    return items


def variant(bt):
    return "".join(p.capitalize() for p in bt.split("_")) if bt != "NONASCII" else "NonAscii"


VARIANTS = {
    "NONXML": "NonXml", "MALFORM": "Malform", "LT": "Lt", "AMP": "Amp", "RSQB": "Rsqb",
    "LEAD2": "Lead2", "LEAD3": "Lead3", "LEAD4": "Lead4", "TRAIL": "Trail", "CR": "Cr",
    "LF": "Lf", "GT": "Gt", "QUOT": "Quot", "APOS": "Apos", "EQUALS": "Equals",
    "QUEST": "Quest", "EXCL": "Excl", "SOL": "Sol", "SEMI": "Semi", "NUM": "Num",
    "LSQB": "Lsqb", "S": "S", "NMSTRT": "Nmstrt", "COLON": "Colon", "HEX": "Hex",
    "DIGIT": "Digit", "NAME": "Name", "MINUS": "Minus", "OTHER": "Other",
    "NONASCII": "NonAscii", "PERCNT": "Percnt", "LPAR": "Lpar", "RPAR": "Rpar",
    "AST": "Ast", "PLUS": "Plus", "COMMA": "Comma", "VERBAR": "Verbar",
}


def rust_bt_array(const, items, doc):
    out = ["/// " + doc, "pub(super) const %s: [ByteType; 128] = [" % const]
    for i in range(0, 128, 4):
        out.append("    " + " ".join("ByteType::%s," % VARIANTS[x] for x in items[i:i + 4]))
    out.append("];")
    return "\n".join(out)


def chartab():
    parts = [HEADER.format(src="asciitab.h, iasciitab.h, latin1tab.h, utf8tab.h"),
             "use super::ByteType;\n"]
    parts.append(rust_bt_array("ASCII_LOWER", bt_list("asciitab.h"),
                               "`asciitab.h`: bytes 0x00-0x7F of the external encodings."))
    parts.append(rust_bt_array("IASCII_LOWER", bt_list("iasciitab.h"),
                               "`iasciitab.h`: like `ASCII_LOWER` but 0x0D is `S` (internal encodings)."))
    parts.append(rust_bt_array("LATIN1_UPPER", bt_list("latin1tab.h"),
                               "`latin1tab.h`: bytes 0x80-0xFF of ISO-8859-1 (and UTF-16 units < 0x100)."))
    parts.append(rust_bt_array("UTF8_UPPER", bt_list("utf8tab.h"),
                               "`utf8tab.h`: bytes 0x80-0xFF of UTF-8."))
    return "\n".join(parts) + "\n"


def c_array(src, name):
    m = re.search(r"static const unsigned(?: char)? %s\[\] = \{(.*?)\};" % name, src, re.S)
    return [int(x, 0) for x in re.findall(r"0x[0-9A-Fa-f]+|\b\d+\b", strip_comments(m.group(1)))]


def naming():
    src = open(os.path.join(LIB, "nametab.h")).read()
    bitmap = c_array(src, "namingBitmap")
    nmstrt = c_array(src, "nmstrtPages")
    name = c_array(src, "namePages")
    assert len(nmstrt) == 256 and len(name) == 256, (len(nmstrt), len(name))
    out = [HEADER.format(src="nametab.h")]
    out.append("/// `namingBitmap`: 256-bit pages; bit `lo & 31` of word `(page << 3) + (lo >> 5)`.")
    out.append("pub(super) const NAMING_BITMAP: [u32; %d] = [" % len(bitmap))
    for i in range(0, len(bitmap), 4):
        out.append("    " + " ".join("0x%08X," % x for x in bitmap[i:i + 4]))
    out.append("];")
    for const, arr, doc in (("NMSTRT_PAGES", nmstrt, "`nmstrtPages`: page of `NAMING_BITMAP` for name-start characters, by high byte."),
                            ("NAME_PAGES", name, "`namePages`: page of `NAMING_BITMAP` for name characters, by high byte.")):
        out.append("/// " + doc)
        out.append("pub(super) const %s: [u8; 256] = [" % const)
        for i in range(0, 256, 16):
            out.append("    " + " ".join("0x%02X," % x for x in arr[i:i + 16]))
        out.append("];")
    return "\n".join(out) + "\n"


def main():
    targets = {
        os.path.join(ROOT, "crates/expat/src/chartab/data.rs"): chartab(),
        os.path.join(ROOT, "crates/expat/src/naming/data.rs"): naming(),
    }
    check = "--check" in sys.argv
    stale = []
    for path, text in targets.items():
        old = open(path).read() if os.path.exists(path) else None
        if old != text:
            stale.append(path)
            if not check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                open(path, "w").write(text)
    if check and stale:
        print("gen_tables: out of date: " + ", ".join(stale))
        sys.exit(1)
    print("gen_tables: %s" % ("OK" if check else "wrote %d file(s)" % len(stale)))


if __name__ == "__main__":
    main()
